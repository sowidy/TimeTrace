"""报告邮件推送：每天 00:03 给订阅用户发送前一天的完整报告 —— 默认平时
发日报，报告日为周日时发整周（周一..周日）的聚合周报，见下面第 ⑤ 条。

    次日发送涉及日期换算，写之前先说清楚几个坑：

    ① 为什么是次日 00:03
       23:59:59 时当天尚未结束，最后的本地统计与上传也可能还在进行。改到
       第二天 00:03，可以覆盖完整自然日，并给客户端留出 3 分钟完成末尾上报。
       因此触发日期不能直接当报告日期：某天 00:03 发送的是前一天。

    ② 定时器不能只「睡到 00:03 然后发昨天」
       服务器可能被重启、被挂起、时钟被 NTP 往回拨。醒来的时候如果已经
       是 00:05 甚至跨到下一天，不能按醒来时的 `date.today()` 推算。因此
       这里记的是**本次唤醒对应的计划时刻**（fire time），报告日恒定为
       `fire.date() - 1 day`。睡过头也只会补发正确日期，不会发错天。

    ③ 发过没有必须落库
       光靠内存里的标记，半夜重启一次就会重发。「同一天同一种报告只发一封」
       最终由 mail_log 表的 UNIQUE KEY 保证（见 db/schema.sql）。

    ④ 失败要留痕
       用户收不到邮件是会来问的，所以失败也写进 mail_log，并且日志里带上
       完整的 SMTP 报错。绝不允许「悄悄吞掉」。

    ⑤ 日报和周报是两种模板，种类由调用方指定
       报告种类（日报 / 周报）不再是「报告日是星期几」的纯函数 —— 日报和
       周报是两种模板，任何一天都可以套用任一种。调用方传 weekly=true 发
       周报（覆盖「以该天结尾的 7 天」的聚合，周一..周日），weekly=false 发
       当天日报，不传则按星期几默认（周日发周报）。定时器不传 weekly，所以
       仍按星期几走；手工触发时传 weekly 就能指定种类。
       因此同一天可能长出两封邮件，③ 里那个 UNIQUE KEY 已放宽成
       (user_key, day, weekly)，见 db/schema.sql。

关于多 worker：定时器是**进程内**的。用 `uvicorn --workers N` 启动时会有
N 个定时器同时到点，它们靠 mail_log 的唯一键互相兜底（重复的那封会在写
记录时撞键），但严格来说「查过没发」和「写记录」之间仍有竞态窗口，理论上
可能重复发一封。要么单 worker 跑（这个服务的量级完全够），要么关掉
进程内定时器（PCTIME_MAIL_SCHEDULER=0），改由外部 cron 调
POST /api/v1/admin/daily-mail。

按「一条责任一个文件」拆开，依赖方向是单向的 report ← sender ← scheduler：
    report.py     正文渲染：秒数格式化、纯文本 / HTML 两个版本、拼成一封信
    sender.py     SMTP 发信，以及「给一个用户发某天」「给所有人发某天」两层
    scheduler.py  进程内的每日定时器（含次日 00:03、日期换算和补发逻辑）

配置一律写成 `config.XXX` 属性访问，**不要** `from config import XXX` ——
测试是靠 `mock.patch.object(config, ...)` 换配置的，`from ... import` 会在导入
时把值复制成一份，patch 就静默失效了。
"""
